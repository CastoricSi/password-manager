// Fills the Worker's Google secrets from the local `secret/` folder.
//
//   npm run secrets:dev    → writes .dev.vars (local development)
//   npm run secrets:prod   → uploads them to Cloudflare (wrangler secret bulk)
//
// Expected files in secret/ (the folder is git-ignored):
//   client_secret.json   OAuth client JSON downloaded from Google Cloud
//   api_key.txt          browser API key (Google Picker)
//   project_number.txt   Cloud project number
//   session_secret.txt   created automatically on first run; keep it stable,
//                        changing it signs everyone out of Google sync

import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "secret");
const mode = process.argv[2];
const ifPresent = process.argv.includes("--if-present");

if (mode !== "dev" && mode !== "prod") {
	console.error("Usage: node scripts/secrets.mjs dev|prod [--if-present]");
	process.exit(1);
}

if (!existsSync(dir)) {
	if (ifPresent) process.exit(0); // e.g. `npm run dev` on a machine without secrets
	console.error("No secret/ folder found. See README → 开启谷歌同步与分享.");
	process.exit(1);
}

const read = (name) => {
	const file = join(dir, name);
	if (!existsSync(file)) {
		console.error(`Missing secret/${name}`);
		process.exit(1);
	}
	return readFileSync(file, "utf8").trim();
};

// OAuth client ("web" key in Google's JSON).
let client;
try {
	const json = JSON.parse(read("client_secret.json"));
	client = json.web ?? json.installed;
} catch {
	console.error("secret/client_secret.json is not valid JSON");
	process.exit(1);
}
if (!client?.client_id || !client?.client_secret) {
	console.error("secret/client_secret.json has no client_id / client_secret");
	process.exit(1);
}

const apiKey = read("api_key.txt");
const projectNumber = read("project_number.txt");
if (!/^\d+$/.test(projectNumber)) {
	console.error("secret/project_number.txt must contain only the project number (digits)");
	process.exit(1);
}

// Stable session secret, generated once.
const sessionFile = join(dir, "session_secret.txt");
if (!existsSync(sessionFile)) {
	writeFileSync(sessionFile, randomBytes(32).toString("base64url") + "\n");
	console.log("Created secret/session_secret.txt");
}
const sessionSecret = read("session_secret.txt");

const secrets = {
	GOOGLE_CLIENT_ID: client.client_id,
	GOOGLE_CLIENT_SECRET: client.client_secret,
	SESSION_SECRET: sessionSecret,
	GOOGLE_API_KEY: apiKey,
	GOOGLE_APP_ID: projectNumber,
};

const callbacks = client.redirect_uris ?? [];

if (mode === "dev") {
	if (!callbacks.includes("http://localhost:5173/api/auth/google/callback")) {
		console.warn("Warning: the OAuth client has no redirect URI http://localhost:5173/api/auth/google/callback — Google sign-in won't work in dev.");
	}
	const body = Object.entries(secrets).map(([k, v]) => `${k}=${v}`).join("\n");
	writeFileSync(join(root, ".dev.vars"), `# Generated by \`npm run secrets:dev\` from secret/ — do not edit or commit.\n${body}\n`);
	console.log("Wrote .dev.vars (" + Object.keys(secrets).join(", ") + ")");
} else {
	console.log("Uploading " + Object.keys(secrets).join(", ") + " to Cloudflare…");
	const res = spawnSync("npx", ["wrangler", "secret", "bulk"], {
		cwd: root,
		input: JSON.stringify(secrets),
		stdio: ["pipe", "inherit", "inherit"],
		shell: process.platform === "win32",
	});
	if (res.status !== 0) {
		console.error("wrangler secret bulk failed (are you logged in? run: npx wrangler login)");
		process.exit(res.status ?? 1);
	}
	const prodCallbacks = callbacks.filter((u) => u.startsWith("https://"));
	if (prodCallbacks.length) console.log("Google sign-in will work on: " + prodCallbacks.map((u) => new URL(u).origin).join(", "));
}
